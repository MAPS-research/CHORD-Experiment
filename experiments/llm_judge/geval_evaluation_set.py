"""G-Eval coherence scores on the counterfactual evaluation set.

Produces the "G-Eval (same Qwen3.5-27B)" row of the appendix table
tab:judge-counterfactual. G-Eval (Liu et al., EMNLP 2023): the released
SummEval coherence rubric, reframed for a standalone passage (there is no
source document), evaluation steps generated once by the judge and then frozen,
and a probability-weighted score sum_s p(s) * s over the rating tokens 1..5 read
from the first generated rating token's top log-probabilities (temperature 0).
The judge is the same Qwen3.5-27B snapshot CHORD uses as its encoder, served as
for ``judge_evaluation_set``.

The frozen evaluation steps used in the paper ship as
``experiments/llm_judge/configs/geval_evaluation_steps.txt`` and are used when
``evaluation_steps_file`` is set in the config; without it the steps are
generated by the judge and frozen to ``<values_dir>/evaluation_steps.txt``.

    python -m experiments.llm_judge.geval_evaluation_set \\
        --config experiments/llm_judge/configs/geval.yaml \\
        --corpus-dir outputs/counterfactual/meta_eval

Scores land in ``<corpus-dir>/<values_dir>/<set>.npy`` (scalar lane of
``experiments.counterfactual_eval.baseline_selectivity``; see judge_evaluation_set for the
scoring command). Responses are cached by (model, prompt revision, steps hash,
text hash).
"""

from __future__ import annotations

import argparse
import json
import math
import random
import threading
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import yaml

from chord.utils.hashing import sha256_text

from ..counterfactual_eval.featurize import _load_texts, _set_path, text_set_names

# Part of every cache key: changing the prompt must change this string.
PROMPT_REVISION = "geval-coh-v1"
SCORE_TOKENS = ("1", "2", "3", "4", "5")

INTRO = (
    "You will be given one passage of English text.\n\n"
    "Your task is to rate the passage on one metric.\n\n"
    "Please make sure you read and understand these instructions carefully. "
    "Please keep this document open while reviewing, and refer to it as needed.\n"
)
# The first sentence of the definition is the DUC coherence question verbatim.
CRITERIA = (
    "Evaluation Criteria:\n\n"
    "Coherence (1-5) - the collective quality of all sentences. We align this "
    "dimension with the DUC quality question of structure and coherence whereby "
    '"the passage should be well-structured and well-organized. The passage '
    "should not just be a heap of related information, but should build from "
    'sentence to sentence to a coherent body of information about a topic." '
    "The passage may be cut off at its very end; do not penalize that.\n"
)
# The released steps, adapted from summary-vs-article to a standalone passage.
FALLBACK_STEPS = (
    "1. Read the passage carefully and identify its main topic and key points.\n"
    "2. Check whether the sentences build on one another in a clear and logical "
    "order and whether the passage forms a coherent body of information about "
    "its topic, rather than a heap of related sentences.\n"
    "3. Assign a score for coherence on a scale of 1 to 5, where 1 is the lowest "
    "and 5 is the highest based on the Evaluation Criteria."
)
STEPS_REQUEST = (
    "\nWrite the Evaluation Steps for this metric as a short numbered list of "
    "three to five concrete steps a rater should follow. Output only the numbered "
    "list.\n\nEvaluation Steps:\n"
)


def build_prompt(steps: str, text: str) -> str:
    return (
        f"{INTRO}\n{CRITERIA}\nEvaluation Steps:\n\n{steps.strip()}\n\n\n"
        f"Example:\n\n\nPassage:\n\n{text}\n\n\nEvaluation Form (scores ONLY):\n\n"
        "- Coherence:"
    )


def expected_score(logprob_content: List[Dict[str, Any]]) -> Tuple[float, float, str]:
    """Probability-weighted rating from a chat-completions ``logprobs.content`` list.

    Uses the first generated token that is a rating digit and takes the
    expectation over the digit tokens in its top_logprobs (renormalized).
    -> (score, digit probability mass covered, greedy digit); NaN if no digit.
    """
    for item in logprob_content or []:
        tok = str(item.get("token", "")).strip()
        if tok not in SCORE_TOKENS:
            continue
        mass: Dict[str, float] = {}
        for cand in item.get("top_logprobs") or []:
            cand_tok = str(cand.get("token", "")).strip()
            if cand_tok in SCORE_TOKENS:
                mass[cand_tok] = mass.get(cand_tok, 0.0) + math.exp(float(cand["logprob"]))
        if not mass:  # no top_logprobs: fall back to the greedy digit
            mass = {tok: math.exp(float(item.get("logprob", 0.0)))}
        total = sum(mass.values())
        score = sum(int(k) * v for k, v in mass.items()) / total
        return float(score), float(total), tok
    return float("nan"), 0.0, ""


def _post(base_url: str, payload: Dict[str, Any], timeout: int) -> Dict[str, Any]:
    req = urllib.request.Request(
        base_url.rstrip("/") + "/chat/completions",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


class GEvalClient:
    """Thread-safe scorer with a (model, prompt revision, steps, text) response cache."""

    def __init__(self, cfg: Dict, cache_path: Path, steps: str) -> None:
        self.cfg = cfg
        self.model = str(cfg["model"])
        self.base_url = str(cfg.get("base_url", "http://127.0.0.1:8000/v1"))
        self.steps = steps
        self.steps_hash = sha256_text(steps)[:16]
        self.cache_path = cache_path
        self._lock = threading.Lock()
        self._dirty = 0
        self.cache: Dict[str, Dict] = {}
        if cache_path.is_file():
            self.cache = json.loads(cache_path.read_text(encoding="utf-8"))

    def _key(self, text: str) -> str:
        return sha256_text(f"{self.model}:{PROMPT_REVISION}:{self.steps_hash}:{sha256_text(text)}")

    def payload(self, prompt: str) -> Dict[str, Any]:
        payload: Dict[str, Any] = {
            "model": self.model,
            "messages": [{"role": "user", "content": prompt}],
            "seed": int(self.cfg.get("seed", 0)),
            "temperature": float(self.cfg.get("temperature", 0.0)),
            "max_tokens": int(self.cfg.get("max_completion_tokens", 8)),
            "logprobs": True,
            "top_logprobs": int(self.cfg.get("top_logprobs", 20)),
        }
        if self.cfg.get("chat_template_kwargs"):
            payload["chat_template_kwargs"] = self.cfg["chat_template_kwargs"]
        return payload

    def request(self, prompt: str) -> Dict[str, Any]:
        """Chat completion with retries on 429 / 5xx / network errors."""
        retries = int(self.cfg.get("max_retries", 5))
        timeout = int(self.cfg.get("timeout_seconds", 180))
        seed = int(self.cfg.get("seed", 0))
        for attempt in range(retries + 1):
            try:
                return _post(self.base_url, self.payload(prompt), timeout)
            except urllib.error.HTTPError as exc:
                body = exc.read().decode("utf-8", errors="replace")
                if not (exc.code == 429 or 500 <= exc.code < 600) or attempt >= retries:
                    raise RuntimeError(f"HTTP {exc.code}: {body[:300]}") from exc
            except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
                if attempt >= retries:
                    raise RuntimeError(f"request failed: {exc}") from exc
            time.sleep(2.0 * (2**attempt) + random.Random(seed + attempt).uniform(0, 2.0))
        raise AssertionError("unreachable")

    def score_one(self, text: str) -> Dict[str, Any]:
        """-> {"score": float (NaN on failure), "mass": float, "greedy": str, "raw": str}."""
        key = self._key(text)
        with self._lock:
            hit = self.cache.get(key)
        if hit is not None:
            return hit
        try:
            result = self.request(build_prompt(self.steps, text))
            choice = result["choices"][0]
            raw = str(choice["message"].get("content", ""))
            content = (choice.get("logprobs") or {}).get("content") or []
            score, mass, greedy = expected_score(content)
            if not np.isfinite(score):
                raise ValueError(f"no rating digit in completion: {raw!r}")
            out = {"score": score, "mass": mass, "greedy": greedy, "raw": raw}
        except Exception as exc:  # noqa: BLE001 - keep the run alive, record NaN
            return {"score": float("nan"), "mass": 0.0, "greedy": "", "raw": f"__error__: {exc}"}
        with self._lock:
            self.cache[key] = out
            self._dirty += 1
            flush = self._dirty >= int(self.cfg.get("flush_every", 200))
        if flush:
            self.flush()
        return out

    def flush(self) -> None:
        self.cache_path.parent.mkdir(parents=True, exist_ok=True)
        with self._lock:
            payload = json.dumps(self.cache, ensure_ascii=False)
            self._dirty = 0
            tmp = self.cache_path.with_suffix(f".tmp{threading.get_ident()}")
            tmp.write_text(payload, encoding="utf-8")
            tmp.replace(self.cache_path)


def load_or_generate_steps(cfg: Dict, judge_cfg: Dict, steps_path: Path) -> str:
    """Frozen steps from the config's file, else from a previous run, else auto-CoT."""
    shipped = cfg.get("evaluation_steps_file")
    if shipped:
        steps = Path(shipped).read_text(encoding="utf-8").strip()
        print(f"[geval] evaluation steps (shipped) <- {shipped}", flush=True)
        return steps
    if steps_path.is_file():
        print(f"[geval] evaluation steps (frozen) <- {steps_path}", flush=True)
        return steps_path.read_text(encoding="utf-8").strip()
    client = GEvalClient(judge_cfg, steps_path.with_name("_steps_scratch.json"), "")
    payload = client.payload(INTRO + "\n" + CRITERIA + STEPS_REQUEST)
    payload.update({"max_tokens": int(judge_cfg.get("steps_max_tokens", 400)), "logprobs": False})
    payload.pop("top_logprobs", None)
    try:
        result = _post(client.base_url, payload, int(judge_cfg.get("timeout_seconds", 180)))
        steps = str(result["choices"][0]["message"].get("content", "")).strip()
        lines = [ln for ln in steps.splitlines() if ln.strip()]
        if sum(1 for ln in lines if ln.strip()[:1].isdigit()) < 2:
            raise ValueError(f"steps are not a numbered list: {steps!r}")
        steps, source = "\n".join(lines), "auto-CoT (generated by the judge model)"
    except Exception as exc:  # noqa: BLE001
        print(f"[geval] step generation failed ({exc}); using the adapted released steps")
        steps, source = FALLBACK_STEPS, "fallback (adapted released steps)"
    steps_path.parent.mkdir(parents=True, exist_ok=True)
    steps_path.write_text(steps + "\n", encoding="utf-8")
    steps_path.with_suffix(".source.txt").write_text(source + "\n", encoding="utf-8")
    print(f"[geval] evaluation steps [{source}] -> {steps_path}\n{steps}", flush=True)
    return steps


def score_texts(client: GEvalClient, texts: List[str], workers: int):
    scores = np.full(len(texts), np.nan, dtype=np.float64)
    details: List[Dict] = [{} for _ in texts]
    failed = 0
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = {pool.submit(client.score_one, t): i for i, t in enumerate(texts)}
        for fut in as_completed(futures):
            i = futures[fut]
            details[i] = fut.result()
            scores[i] = details[i]["score"]
            failed += int(not np.isfinite(scores[i]))
    return scores, details, failed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    parser.add_argument("--corpus-dir", required=True)
    parser.add_argument("--only-sets", default="", help="comma-separated text sets")
    parser.add_argument("--limit", type=int, default=0, help="first N docs per set (not saved)")
    args = parser.parse_args()
    cfg = yaml.safe_load(Path(args.config).read_text(encoding="utf-8"))
    cdir = Path(args.corpus_dir)
    manifest = json.loads((cdir / "conditions_manifest.json").read_text())
    sets = text_set_names(manifest)
    only = [s.strip() for s in args.only_sets.split(",") if s.strip()]
    if only:
        unknown = [s for s in only if s not in sets]
        if unknown:
            raise SystemExit(f"--only-sets: unknown text sets {unknown}")
        sets = only
    vdir = cdir / str(cfg.get("values_dir", "geval"))
    vdir.mkdir(parents=True, exist_ok=True)
    judge_cfg = cfg["judge"]
    steps = (
        load_or_generate_steps(cfg, judge_cfg, vdir / "evaluation_steps.txt")
        if bool(cfg.get("auto_cot", True))
        else FALLBACK_STEPS
    )
    client = GEvalClient(judge_cfg, vdir / "geval_cache.json", steps)
    workers = int(cfg.get("concurrency", 32))

    for name in sets:
        out = vdir / f"{name}.npy"
        if out.exists() and not args.limit:
            print(f"[geval] {name} exists, skip", flush=True)
            continue
        texts = _load_texts(_set_path(cdir / "texts", name))[: args.limit or None]
        scores, details, failed = score_texts(client, texts, workers)
        mass = np.nanmean([d.get("mass", 0.0) for d in details])
        msg = f"n={len(texts)} mean={np.nanmean(scores):.3f} digit-mass={mass:.3f} failed={failed}"
        if args.limit:
            print(f"[geval] {name} (limit, not saved): {msg}", flush=True)
            continue
        np.save(out, scores)
        with open(vdir / f"{name}.details.jsonl", "w", encoding="utf-8") as fh:
            for i, d in enumerate(details):
                fh.write(json.dumps({"idx": i, **d}, ensure_ascii=False) + "\n")
        client.flush()
        print(f"[geval] {name}: {msg}", flush=True)
    client.flush()
    print(f"[geval] done -> {vdir}", flush=True)


if __name__ == "__main__":
    main()
